def get_account():
    """Get the fixed demo customer's account from Snowflake."""
    with closing(get_snowflake()) as conn:
        with closing(conn.cursor()) as cursor:
            cursor.execute(
                """
                SELECT CUSTOMER_NAME, ACCOUNT_ID, BALANCE, CURRENCY
                FROM ACCOUNTS
                WHERE ACCOUNT_ID = %s
                """,
                ("ACC001",),
            )
            row = cursor.fetchone()

    if row is None:
        return {"error": "Demo account not found"}

    return {
        "name": row[0],
        "account_number": row[1],
        "balance": float(row[2]),
        "currency": row[3],
        "source": "Snowflake",
    }

