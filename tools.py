def get_ticket_status(ticket_id: str):
    """Look up a Salesforce Case using its Case Number, preserving leading zeros."""
    sf = get_salesforce()

    query = format_soql(
        "SELECT CaseNumber, Subject, Status, Description "
        "FROM Case WHERE CaseNumber = {} LIMIT 1",
        ticket_id,
    )

    records = sf.query(query)["records"]

    if not records:
        return {"error": "No Salesforce Case found with that number"}

    case = records[0]

    return {
        "ticket_id": case["CaseNumber"],
        "status": case["Status"],
        "issue": case["Subject"],
        "description": case["Description"],
        "source": "Salesforce",
    }

def create_ticket(issue: str):
    """Create a Salesforce support Case when the customer explicitly requests it."""
    issue = issue.strip()

    if not issue:
        return {"error": "An issue description is required"}

    sf = get_salesforce()

    result = sf.Case.create({
        "Subject": f"Demo — {issue}"[:255],
        "Description": issue,
        "Status": "New",
        "Origin": "Web",
        "Priority": "Medium",
    })

    if not result.get("success"):
        return {"error": "Salesforce could not create the Case"}

    # Retrieve the Case Number generated by Salesforce.
    case = sf.Case.get(result["id"])

    return {
        "ticket_id": case["CaseNumber"],
        "salesforce_id": result["id"],
        "status": case["Status"],
        "issue": case["Subject"],
        "source": "Salesforce",
    }
